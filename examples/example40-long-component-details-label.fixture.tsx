import { SchematicComponentDetailsTooltip } from "lib/components/SchematicComponentDetailsTooltip"
import { renderToCircuitJson } from "lib/dev/render-to-circuit-json"

// Compile a real component. The core creates the internal source-port IDs.
const circuitJson = renderToCircuitJson(
  <board>
    <pushbutton name="SW1" internallyConnectedPins={[[1, 2]]} />
  </board>,
)

const switchSourceComponent = circuitJson.find(
  (element) => element.type === "source_component" && element.name === "SW1",
)

if (switchSourceComponent?.type !== "source_component") {
  throw new Error("SW1 was not generated by @tscircuit/core")
}

export default () => (
  <div style={{ position: "relative", minHeight: 340, background: "#f8fafc" }}>
    <p style={{ margin: 16, fontFamily: "sans-serif" }}>
      Component details generated by @tscircuit/core; internal IDs should be
      hidden.
    </p>
    <SchematicComponentDetailsTooltip
      sourceComponent={switchSourceComponent}
      left={16}
      top={60}
      width={560}
      maxHeight={260}
    />
  </div>
)
